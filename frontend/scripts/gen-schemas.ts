// Copies JSON Schemas of the api's DTOs out of ../api/openapi.json, for forms generated from them (svelte-jsonschema-form).
// Part of `bun run gen:api`; the output is committed, since the frontend's container build can't read ../api.
import { readFileSync, writeFileSync } from 'node:fs';

/** Component schemas to export, by their name in openapi.json. */
const SCHEMAS = ['Settings'];

const spec: { components: { schemas: Record<string, unknown> } } = JSON.parse(
  readFileSync('../api/openapi.json', 'utf8'),
);

const lines = ['// Generated by scripts/gen-schemas.ts from api/openapi.json; do not edit.', ''];
for (const name of SCHEMAS) {
  const schema = spec.components.schemas[name];
  if (!schema) throw new Error(`No schema "${name}" in openapi.json`);
  lines.push(
    `export const ${name.charAt(0).toLowerCase()}${name.slice(1)}JsonSchema = ${JSON.stringify(schema)} as const;`,
  );
}
writeFileSync('src/lib/types/schemas.ts', `${lines.join('\n')}\n`);
